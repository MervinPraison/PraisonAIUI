"""Turn an ``AiuiDraft`` into an ``aiui.template.yaml`` document.

The shape is the docs shell ``aiui build`` already accepts. This module does
not call the compiler.
"""

from __future__ import annotations

from typing import Any, Optional

import yaml

from praisonaiui.mkdocs_import.model import AiuiDraft, Finding

_INCLUDE = ["**/*.md", "**/*.mdx"]


def build_document(draft: AiuiDraft) -> dict[str, Any]:
    """The config mapping, before comments are added."""
    site: dict[str, Any] = {
        "title": draft.site_title,
        "ui": "shadcn",
        "theme": _theme(draft),
    }
    if draft.site_description:
        site["description"] = draft.site_description

    document: dict[str, Any] = {"schemaVersion": 1, "site": site}

    if draft.site_url:
        document["seo"] = {"siteUrl": draft.site_url}

    navigation = _navigation(draft)
    if navigation:
        document["navigation"] = navigation

    if draft.repo_url:
        document["navbar"] = {"links": [{"label": "GitHub", "href": draft.repo_url}]}

    if draft.socials:
        document["footer"] = {"socials": dict(draft.socials)}

    document["search"] = {
        "enabled": draft.search_enabled,
        "provider": "fusejs",
    }

    docs: dict[str, Any] = {"dir": draft.docs_dir, "include": list(_INCLUDE)}
    if draft.exclude:
        docs["exclude"] = list(draft.exclude)
    document["content"] = {"docs": docs}

    logo = draft.site_title
    footer_text = draft.copyright or draft.site_title
    document["templates"] = {
        "docs": {
            "layout": "ThreeColumnLayout",
            "slots": {
                "header": {"ref": "header_main"},
                "left": {"ref": "sidebar_docs"},
                "main": {"type": "DocContent"},
                "footer": {"ref": "footer_main"},
            },
        }
    }
    document["components"] = {
        "header_main": {"type": "Header", "props": {"logoText": logo}},
        "footer_main": {"type": "Footer", "props": {"text": footer_text}},
        "sidebar_docs": {"type": "DocsSidebar", "props": {"source": "docs-nav"}},
    }
    document["routes"] = [{"match": "/docs/**", "template": "docs"}]

    for key, value in draft.overlay.items():
        document[key] = value
    return document


def render_yaml(
    draft: AiuiDraft,
    findings: list[Finding],
    *,
    source_name: str,
) -> tuple[str, dict[str, Any]]:
    """Return ``(yaml text, document)``. Dropped findings are listed as comments."""
    document = build_document(draft)
    body = yaml.safe_dump(
        document,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
    )
    header = _header(findings, source_name)
    return header + body, document


def _theme(draft: AiuiDraft) -> dict[str, Any]:
    """Paper is the PraisonAI UI docs default. ``mode`` wins over ``darkMode``."""
    theme: dict[str, Any] = {"preset": draft.preset, "radius": "md"}
    if draft.mode:
        theme["mode"] = draft.mode
    else:
        theme["darkMode"] = draft.dark_mode
    return theme


def _navigation(draft: AiuiDraft) -> Optional[dict[str, Any]]:
    if not draft.tabs:
        return None
    tabs: list[dict[str, Any]] = []
    for tab in draft.tabs:
        groups: list[dict[str, Any]] = []
        for group in tab.groups:
            item: dict[str, Any] = {"group": group.group, "pages": list(group.pages)}
            if group.prefix:
                item["prefix"] = group.prefix
            groups.append(item)
        if groups:
            tabs.append({"tab": tab.tab, "groups": groups})
    if not tabs:
        return None
    return {"tabs": tabs}


def _header(findings: list[Finding], source_name: str) -> str:
    lines = [
        f"# Generated by praisonaiui.mkdocs_import from {source_name}.",
        "# The MkDocs file is left unchanged. aiui build reads this file.",
    ]
    for finding in findings:
        if finding.level == "dropped":
            lines.append(f"# Dropped: {finding.message}")
    lines.append("")
    return "\n".join(lines)
